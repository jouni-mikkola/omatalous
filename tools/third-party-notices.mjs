import { existsSync, readdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
// Usage: node tools/third-party-notices.mjs [--check]
// Writes THIRD_PARTY_NOTICES: the licence of every package that runs in the app (the runtime dependencies of
// apps/server and apps/web, and theirs in turn), read from node_modules. The server bundle and the web build carry
// these packages' code, and MIT and similar licences require the notice to travel with it. --check fails when the
// file is out of date.
const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const APPS = ["apps/server", "apps/web"];
const LICENCE_FILE = /^(licen[cs]e|copying|notice)(\.|$|-)/i;

const readJson = (file) => JSON.parse(readFileSync(file, "utf8"));

/** The directory of dependency `name` as seen from package directory `from`: the nearest node_modules up the tree. */
function resolveDep(from, name) {
  for (let dir = from; ; dir = dirname(dir)) {
    const p = join(dir, "node_modules", name);
    if (existsSync(join(p, "package.json"))) return realpathSync(p);
    if (dirname(dir) === dir) return null;
  }
}

/** The packages that run in the app, once each, sorted by name and version. Workspace packages are ours and left out. */
export function collect(root = ROOT, apps = APPS) {
  const seen = new Map();
  const walk = (dir) => {
    const pkg = readJson(join(dir, "package.json"));
    for (const name of [...Object.keys(pkg.dependencies ?? {}), ...Object.keys(pkg.optionalDependencies ?? {})]) {
      const at = resolveDep(dir, name);
      if (!at) continue;
      const dep = readJson(join(at, "package.json"));
      if (dep.private) {
        walk(at);
        continue;
      }
      const key = `${dep.name}@${dep.version}`;
      if (seen.has(key)) continue;
      seen.set(key, { name: dep.name, version: dep.version, license: licenceField(dep), homepage: dep.homepage ?? "", texts: licenceTexts(at) });
      walk(at);
    }
  };
  for (const app of apps) walk(join(root, app));
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

function licenceField(pkg) {
  const l = pkg.license ?? pkg.licenses;
  if (typeof l === "string") return l;
  if (Array.isArray(l)) return l.map((x) => x.type ?? x).join(" OR ");
  return l?.type ?? "UNKNOWN";
}

function licenceTexts(dir) {
  return readdirSync(dir)
    .filter((f) => LICENCE_FILE.test(f))
    .sort()
    .map((f) => readFileSync(join(dir, f), "utf8").trim())
    .filter(Boolean);
}

/** The file: a header, then each package with its licence and the texts it ships. */
export function render(packages) {
  const out = [
    "Third-party notices",
    "",
    "Omatalous carries the packages below. Each is under its own licence, given here as the package ships it.",
    "The licence of Omatalous itself is in LICENSE. Generated by tools/third-party-notices.mjs; do not edit by hand.",
  ];
  for (const p of packages) {
    out.push("", "=".repeat(78), `${p.name} ${p.version} (${p.license})`);
    if (p.homepage) out.push(p.homepage);
    if (p.texts.length === 0) out.push("", "The package ships no licence file; its package.json names the licence above.");
    for (const t of p.texts) out.push("", t);
  }
  return out.join("\n") + "\n";
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const file = join(ROOT, "THIRD_PARTY_NOTICES");
  const text = render(collect());
  if (process.argv.includes("--check")) {
    if (!existsSync(file) || readFileSync(file, "utf8") !== text) {
      console.error("THIRD_PARTY_NOTICES is out of date. Run: node tools/third-party-notices.mjs");
      process.exit(1);
    }
  } else writeFileSync(file, text);
}
