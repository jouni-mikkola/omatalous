/**
 * `pnpm tokens`: writes the two files made from apps/web/design/tokens.json.
 *   apps/web/src/styles/tokens.css   the custom properties, one look, in the `tokens` layer
 *   apps/web/src/design/tokens.ts    the same names and values for code: chart colours, tests, the repo rule
 *
 *   pnpm tokens            write the files that differ
 *   pnpm tokens --check    write nothing; exit 1 and name the file that differs
 *   --root <dir>           another checkout (the test uses a copy)
 *
 * No dependency: plain node with type stripping, like `pnpm findings`.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { cssValue, oklchToHex, plainNumber, readTokens, type Oklch, type Token } from "./dtcg.ts";

export const SOURCE = "apps/web/design/tokens.json";
export const CSS_OUT = "apps/web/src/styles/tokens.css";
export const TS_OUT = "apps/web/src/design/tokens.ts";

const CSS_HEAD = `/*
 * Generated by \`pnpm tokens\` from ${SOURCE}. Do not edit: change the source and run it again.
 * One look, a light one. There is no second set, no light-dark(), no prefers-color-scheme and no attribute that switches
 * it: a part that needs another value is a missing token. A token is the file's key with two dashes in front. Measures that change with the room or the
 * pointer are the media rules at the end.
 */`;

const TS_HEAD = `// Generated by \`pnpm tokens\` from ${SOURCE}. Do not edit: change the source and run it again.`;

const decl = (t: Token): string => `--${t.key}: ${cssValue(t, t.value)};`;

/** The text of tokens.css. */
export function renderCss(tokens: Token[]): string {
  const body = tokens.map((t) => `  ${decl(t)}`).join("\n");
  const queries = new Map<string, string[]>();
  for (const t of tokens) for (const [q, v] of t.media) queries.set(q, [...(queries.get(q) ?? []), `    --${t.key}: ${cssValue(t, v)};`]);
  const media = [...queries].map(([q, rules]) => `@media ${q} {\n  :root {\n${rules.join("\n")}\n  }\n}`).join("\n");
  return `${CSS_HEAD}\n@layer tokens {\n:root {\n  color-scheme: light;\n${body}\n}\n${media}\n}\n`;
}

const quoted = (k: string): string => (/^[a-z_][a-z0-9_]*$/i.test(k) ? k : JSON.stringify(k));
const entries = (pairs: [string, string | number][]): string => pairs.map(([k, v]) => `  ${quoted(k)}: ${JSON.stringify(v)},`).join("\n");

/** The text of tokens.ts. */
export function renderTs(tokens: Token[]): string {
  const colors = tokens.filter((t) => t.group === "color");
  const series = colors.filter((t) => /^series-\d+$/.test(t.key)).sort((a, b) => Number(a.key.slice(7)) - Number(b.key.slice(7)));
  const opaque = colors.filter((t) => typeof t.value === "object" && (t.value as Oklch).alpha === undefined);
  const px = (group: string, strip = ""): [string, number][] =>
    tokens.filter((t) => t.group === group).map((t) => [t.key.replace(strip, ""), plainNumber(t.value)!]);
  const fontSizes = px("font").filter(([k]) => k.startsWith("fs-")).map(([k, v]): [string, number] => [k.slice(3), v]);
  return `${TS_HEAD}

/** Every token name, as the CSS custom property it is (\`--page\`). */
export const cssNames = ${JSON.stringify(tokens.map((t) => `--${t.key}`), null, 2)} as const;

/** A colour token as the CSS value that reads it: \`color.bad\` is \`"var(--bad)"\`. Charts and code take colours from here. */
export const color = {
${entries(colors.map((t) => [t.key, `var(--${t.key})`]))}
} as const;
export type ColorToken = keyof typeof color;

/** The category palette in its fixed order: the same series is the same colour on every chart. */
export const series = [${series.map((t) => `color["${t.key}"]`).join(", ")}] as const;
export type SeriesColor = (typeof series)[number];

/** The opaque colours as #rrggbb, for the contrast test and for a canvas that cannot read a variable. */
export const hex = {
${entries(opaque.map((t) => [t.key, oklchToHex(t.value as Oklch)]))}
} as const;

/** The spacing step, in px, by step. */
export const space = {
${entries(px("space", "sp-"))}
} as const;

/** Layout measures, in px, at their widest rule (the value before a media query). */
export const size = {
${entries(px("size"))}
} as const;

/** Font sizes in px by step (\`display\` is 3.25 rem). */
export const fontSize = {
${entries(fontSizes)}
} as const;

/** Durations in ms. They are 0 under \`prefers-reduced-motion\`. */
export const motion = {
${entries(px("motion").filter(([k]) => k.startsWith("t-")).map(([k, v]): [string, number] => [k.slice(2), v]))}
} as const;
`;
}

/** The two outputs of the checkout at `root`, by path. */
export function render(root: string): Record<string, string> {
  const tokens = readTokens(JSON.parse(readFileSync(join(root, SOURCE), "utf8")));
  return { [CSS_OUT]: renderCss(tokens), [TS_OUT]: renderTs(tokens) };
}

/** Writes what differs, or with `check` writes nothing; the paths that differ. */
export function build(root: string, check: boolean): string[] {
  const differs: string[] = [];
  for (const [path, text] of Object.entries(render(root))) {
    const file = join(root, path);
    if (existsSync(file) && readFileSync(file, "utf8") === text) continue;
    differs.push(path);
    if (!check) {
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, text);
    }
  }
  return differs;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const at = args.indexOf("--root");
  const root = at >= 0 ? resolve(args[at + 1] ?? ".") : resolve(dirname(fileURLToPath(import.meta.url)), "../..");
  const check = args.includes("--check");
  try {
    const differs = build(root, check);
    if (check && differs.length) {
      console.error(`pnpm tokens --check: ${differs.join(", ")} differs from ${SOURCE}. Run \`pnpm tokens\` and commit the result.`);
      process.exit(1);
    }
    if (!check) console.log(differs.length ? `pnpm tokens: wrote ${differs.join(", ")}` : "pnpm tokens: nothing to write");
  } catch (e) {
    console.error(e instanceof Error ? e.message : e);
    process.exit(1);
  }
}
