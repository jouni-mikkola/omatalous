// @ts-check
/**
 * `pnpm gen`: writes the registry of each feature kind, `packages/core/src/features/<kind>/registry.gen.ts`, one export
 * line a module folder. The files are tracked and merge by union (`.gitattributes`), so two branches that each add a
 * module land without a conflict; the frame sorts by `order` and `id`, so the order of the lines means nothing.
 *
 *   node tools/gen/registry.mjs            write the registries that differ
 *   node tools/gen/registry.mjs --check    write nothing; exit 1 and say which registry differs
 *   --force                                also sort a registry that has the right lines in another order
 *   --root <dir>                           another checkout (the repo rules and the union scenarios use it)
 *
 * Plain node and no dependency: core is run by four runners, and the generator must run before any of them.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/** The kinds of module, as `FeatureKind` in packages/core/src/features/contract.ts. */
export const KINDS = ["insight", "check", "section", "payee", "question", "notice"];
/** A folder name that is a module id: lower case words joined by single hyphens. It is also an export name (hyphen to underscore). */
export const ID = /^[a-z][a-z0-9]*(-[a-z0-9]+)*$/;
export const FEATURES = "packages/core/src/features";
export const registryPath = (/** @type {string} */ kind) => `${FEATURES}/${kind}/registry.gen.ts`;
export const exportName = (/** @type {string} */ id) => id.replace(/-/g, "_");
export const lineFor = (/** @type {string} */ id) => `export { module as ${exportName(id)} } from "./${id}/index.ts";`;

const HEAD = [
  "// Generated by `pnpm gen` from the folders beside this file: one line a module. Do not edit by hand.",
  "// The order of the lines means nothing: the frame sorts by order and id. The file merges by union (.gitattributes).",
];
// A file needs one export for `import * as all` to be a module; this line is the same on every branch.
const TAIL = "export {};";

/** The module folders of a kind: `ok` hold an index.ts and a valid name; `bad` are listed for the repo rule to name. */
export function folders(/** @type {string} */ root, /** @type {string} */ kind) {
  const dir = join(root, FEATURES, kind);
  /** @type {{ ok: string[], bad: { id: string, why: string }[] }} */
  const out = { ok: [], bad: [] };
  if (!existsSync(dir)) return out;
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (!e.isDirectory()) continue;
    if (!ID.test(e.name)) out.bad.push({ id: e.name, why: "is not a module id (lower case words joined by single hyphens)" });
    else if (!existsSync(join(dir, e.name, "index.ts"))) out.bad.push({ id: e.name, why: "has no index.ts, so the registry cannot export it" });
    else out.ok.push(e.name);
  }
  return out;
}

/** The text of a registry that holds these modules: sorted by id, LF, no date, no path of this machine. */
export function registryText(/** @type {readonly string[]} */ ids) {
  const sorted = [...ids].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  return `${[...HEAD, ...sorted.map(lineFor), TAIL].join("\n")}\n`;
}

/** The text of the registry of a kind in the checkout at `root`. */
export function render(/** @type {string} */ root, /** @type {string} */ kind) {
  return registryText(folders(root, kind).ok);
}

/**
 * What differs between a registry on disk and the generator's text, as sentences. Two registries are the same when
 * they hold the same lines, whatever their order: a union merge puts the lines of two branches one after the other.
 */
export function differences(/** @type {string} */ actual, /** @type {string} */ expected) {
  const count = (/** @type {string} */ t) => {
    /** @type {Map<string, number>} */
    const m = new Map();
    for (const l of t.split("\n")) m.set(l, (m.get(l) ?? 0) + 1);
    return m;
  };
  const a = count(actual);
  const e = count(expected);
  /** @type {string[]} */
  const out = [];
  if (!actual.endsWith("\n") || actual.includes("\r")) out.push("does not end in an LF-terminated line, or holds a CR");
  for (const [l, n] of e) if ((a.get(l) ?? 0) < n) out.push(`lacks: ${l}`);
  for (const [l, n] of a) {
    if (!e.has(l)) out.push(`has a line the folders do not give: ${l}`);
    else if (n > (e.get(l) ?? 0)) out.push(`has a line ${n} times: ${l}`);
  }
  return out;
}

/** Every registry as `path -> text`. */
export function renderAll(/** @type {string} */ root) {
  return new Map(KINDS.map((k) => [registryPath(k), render(root, k)]));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const t0 = performance.now();
  const args = process.argv.slice(2);
  const at = args.indexOf("--root");
  const root = resolve(at >= 0 ? (args[at + 1] ?? ".") : join(dirname(fileURLToPath(import.meta.url)), "../.."));
  const check = args.includes("--check");
  const force = args.includes("--force");
  let stale = 0;
  let modules = 0;
  for (const [path, text] of renderAll(root)) {
    modules += text.split("\n").filter((l) => l.startsWith("export {") && l !== TAIL).length;
    const file = join(root, path);
    const now = existsSync(file) ? readFileSync(file, "utf8") : "";
    if (differences(now, text).length === 0 && (check || !force || now === text)) continue;
    stale++;
    if (check) console.log(`gen: ${path} differs from the folders (run: pnpm gen)`);
    else {
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, text);
    }
  }
  const ms = Math.round(performance.now() - t0);
  console.log(check ? `gen: ${stale ? `${stale} registries differ, run: pnpm gen` : "registries are as the folders say"} (${modules} modules, ${ms} ms)` : `gen: ${KINDS.length} registries, ${modules} modules, ${stale} written (${ms} ms)`);
  process.exit(check && stale ? 1 : 0);
}
